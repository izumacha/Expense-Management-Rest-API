    /** README から DDL のコードブロック（CREATE TABLE ＋ CREATE INDEX）だけを切り出して返す。 */
    private static String readDdlBlock() {
        // README を読む（存在しない・読めないのは環境の異常なので握り潰さず失敗させる。§6）
        String readme;
        try {
            // UTF-8 として README 全体を読み込む
            readme = Files.readString(README_PATH, StandardCharsets.UTF_8);
        } catch (java.io.IOException e) {
            // どのファイルが読めなかったかを添えて停止する
            throw new IllegalStateException("README を読み取れません: " + README_PATH.toAbsolutePath(), e);
        }
        // DDL の開始位置（CREATE TABLE audit_logs）を探す
        int start = readme.indexOf(DDL_START_MARKER);
        // 見つからなければ README 側から DDL が消えている（＝適用手順が失われている）ので失敗させる
        assertThat(start)
                // 失敗時に何が起きたかと直し方を示す
                .as("README に「%s」が見つかりません（本番へ手動適用する DDL が失われていないか確認してください）",
                        DDL_START_MARKER)
                // 見つかった位置は 0 以上になる
                .isNotNegative();
        // DDL ブロックの終わり（次のコードフェンス）を探す
        int end = readme.indexOf(CODE_FENCE, start);
        // 閉じフェンスが無ければ Markdown が壊れているので失敗させる
        assertThat(end)
                // 失敗時に何が起きたかを示す
                .as("README の DDL ブロックを閉じるコードフェンス（%s）が見つかりません", CODE_FENCE)
                // 見つかった位置は 0 以上になる
                .isNotNegative();
        // 開始位置から閉じフェンスの手前までを DDL 本体として返す
        return readme.substring(start, end);
    }

    /** DDL の {@code CREATE TABLE} 部分を解析し、列名から定義を引ける形にして返す。 */
    private static Map<String, DdlColumn> parseColumns(String ddl) {
        // CREATE TABLE の列定義を囲む丸括弧の開き位置を探す
        int open = ddl.indexOf('(');
        // 開き括弧が無ければ DDL の形が想定と違うので失敗させる
        assertThat(open)
                // 失敗時に何が起きたかを示す
                .as("CREATE TABLE の列定義を囲む丸括弧が見つかりません")
                // 見つかった位置は 0 以上になる
                .isNotNegative();
        // 開き括弧に対応する閉じ括弧を探す（入れ子の括弧に耐えるため深さを数える）
        int close = matchingParenthesis(ddl, open);
        // 括弧の内側（列定義の並び）を取り出す
        String body = ddl.substring(open + 1, close);
        // 解析結果を列名で引けるようにする入れ物（定義順を保つ）
        Map<String, DdlColumn> columns = new LinkedHashMap<>();
        // 括弧の深さ 0 のカンマで区切って 1 列ずつ処理する
        for (String definition : splitTopLevel(body)) {
            // 前後の空白を落とす
            String trimmed = definition.trim();
            // 空の要素（末尾のカンマなど）は列ではないので飛ばす
            if (trimmed.isEmpty()) {
                // 次の要素へ進む
                continue;
            }
            // 空白の連続で区切って語に分ける（VARCHAR(64) のように括弧が続く語は 1 語のまま残る）
            String[] tokens = trimmed.split("\\s+");
            // 「列名」「型」の 2 語は最低限必要なので、足りなければ解析できていない
            assertThat(tokens.length)
                    // 失敗時にどの定義でつまずいたかを示す
                    .as("列定義を解析できません（列名と型が読み取れません）: %s", trimmed)
                    // 2 語以上あることを検証する
                    .isGreaterThanOrEqualTo(2);
            // 1 語目が列名（大文字小文字の違いを無視するため小文字にそろえる）
            String name = tokens[0].toLowerCase();
            // 2 語目が型（同じく小文字にそろえる）
            String type = tokens[1].toLowerCase();
            // 3 語目以降の修飾子を 1 つの文字列にまとめる（大文字にそろえて含有判定しやすくする）
            StringBuilder modifiers = new StringBuilder();
            // 3 語目から末尾までを連結する
            for (int i = 2; i < tokens.length; i++) {
                // 語の区切りが消えないよう空白を挟んでから連結する
                modifiers.append(' ').append(tokens[i].toUpperCase());
            }
            // 連結した修飾子を文字列として確定する
            String modifierText = modifiers.toString();
            // 解析した 1 列分を入れ物へ登録する
            columns.put(name, new DdlColumn(
                    // 列名
                    name,
                    // 型
                    type,
                    // NOT NULL が付いているか
                    modifierText.contains("NOT NULL"),
                    // PRIMARY KEY が付いているか
                    modifierText.contains("PRIMARY KEY"),
                    // 自動採番（識別列）として定義されているか
                    modifierText.contains("GENERATED BY DEFAULT AS IDENTITY")));
        }
        // 解析結果を返す
        return columns;
    }

    /** DDL の {@code CREATE INDEX} 文をすべて解析して返す。 */
    private static List<DdlIndex> parseIndexes(String ddl) {
        // 解析結果を集める入れ物
        List<DdlIndex> indexes = new ArrayList<>();
        // 最初の CREATE INDEX を探す
        int cursor = ddl.indexOf(CREATE_INDEX_MARKER);
        // 見つからなくなるまで 1 文ずつ処理する
        while (cursor >= 0) {
            // 対象列を囲む丸括弧の開き位置を探す
            int open = ddl.indexOf('(', cursor);
            // 開き括弧が無ければ文の形が想定と違うので失敗させる
            assertThat(open)
                    // 失敗時に何が起きたかを示す
                    .as("CREATE INDEX の対象列を囲む丸括弧が見つかりません")
                    // 見つかった位置は 0 以上になる
                    .isNotNegative();
            // 開き括弧に対応する閉じ括弧を探す
            int close = matchingParenthesis(ddl, open);
            // 「CREATE INDEX <名前> ON <テーブル>」の部分を語に分ける
            String[] head = ddl.substring(cursor, open).trim().split("\\s+");
            // CREATE / INDEX / 名前 / ON / テーブル名 の 5 語が必要
            assertThat(head.length)
                    // 失敗時にどの文でつまずいたかを示す
                    .as("CREATE INDEX 文を解析できません: %s", String.join(" ", head))
                    // 5 語あることを検証する
                    .isEqualTo(5);
            // 対象列の一覧を組み立てる入れ物
            List<String> indexColumns = new ArrayList<>();
            // 括弧の内側をカンマで区切って 1 列ずつ加える
            for (String column : splitTopLevel(ddl.substring(open + 1, close))) {
                // 前後の空白を落とし小文字にそろえて加える
                indexColumns.add(column.trim().toLowerCase());
            }
            // 解析した 1 つ分を入れ物へ加える（3 語目がインデックス名）
            indexes.add(new DdlIndex(head[2].toLowerCase(), indexColumns));
            // 次の CREATE INDEX を探す
            cursor = ddl.indexOf(CREATE_INDEX_MARKER, close);
        }
        // 解析結果を返す
        return indexes;
    }

    /**
     * {@code open} の位置にある開き括弧に対応する閉じ括弧の位置を返す。
     *
     * <p>単純に最初の {@code ')'} を探すと、{@code NUMERIC(10, 2)} のように型が括弧を持つ列が
     * 増えたときに途中で切れる。深さを数えて対応する側を見つける。
     */
    private static int matchingParenthesis(String text, int open) {
        // 括弧の深さ（開き括弧で増やし閉じ括弧で減らす）
        int depth = 0;
        // 開き括弧の位置から末尾まで 1 文字ずつ走査する
        for (int i = open; i < text.length(); i++) {
            // 現在位置の文字を取り出す
            char c = text.charAt(i);
            // 開き括弧なら深さを 1 つ増やす
            if (c == '(') {
                // 深さを増やす
                depth++;
            } else if (c == ')') {
                // 閉じ括弧なら深さを 1 つ減らす
                depth--;
                // 深さが 0 に戻った位置が対応する閉じ括弧
                if (depth == 0) {
                    // その位置を返す
                    return i;
                }
            }
        }
        // 対応する閉じ括弧が無いのは DDL が壊れているので握り潰さず失敗させる（§6）
        throw new IllegalStateException("対応する閉じ括弧が見つかりません: " + text.substring(open));
    }

    /**
     * 括弧の深さ 0 にあるカンマだけで文字列を区切って返す。
     *
     * <p>{@code String.split(",")} だと型の中のカンマ（{@code NUMERIC(10, 2)}）でも切れてしまうため、
     * 深さを見ながら自前で区切る。
     */
    private static List<String> splitTopLevel(String text) {
        // 区切った結果を集める入れ物
        List<String> parts = new ArrayList<>();
        // 括弧の深さ
        int depth = 0;
        // 直前の区切り位置
        int start = 0;
        // 先頭から末尾まで 1 文字ずつ走査する
        for (int i = 0; i < text.length(); i++) {
            // 現在位置の文字を取り出す
            char c = text.charAt(i);
            // 開き括弧なら深さを増やす
            if (c == '(') {
                // 深さを増やす
                depth++;
            } else if (c == ')') {
                // 閉じ括弧なら深さを減らす
                depth--;
            } else if (c == ',' && depth == 0) {
                // 深さ 0 のカンマは要素の区切りなので、そこまでを 1 要素として切り出す
                parts.add(text.substring(start, i));
                // 次の要素の開始位置を更新する
                start = i + 1;
            }
        }
        // 最後の区切りから末尾までを最終要素として加える
        parts.add(text.substring(start));
        // 区切った結果を返す
        return parts;
    }

